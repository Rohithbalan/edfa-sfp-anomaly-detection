"""Build the submission artefacts from run.py (the single source of truth).

1. Export the Insights and Decision-log markdown cells to insights.md / decision_log.md.
2. Copy outputs/preprocessing_log.md (generated by run.py) to the repository root.
3. Convert run.py to pdm_notebook.ipynb (jupytext) and execute it in place (nbconvert),
   so the notebook carries its outputs.

usage:  python tools/build_deliverables.py [--no-execute]
"""
from __future__ import annotations

import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "run.py"


def markdown_cells(source: str) -> list[str]:
    cells = []
    for chunk in source.split("\n# %%")[1:]:
        header, _, body = chunk.partition("\n")
        if header.strip().startswith("[markdown]"):
            lines = [re.sub(r"^# ?", "", ln) for ln in body.splitlines() if ln.startswith("#")]
            cells.append("\n".join(lines).strip() + "\n")
    return cells


def export_markdown() -> None:
    cells = markdown_cells(SRC.read_text(encoding="utf-8"))
    insights = next(c for c in cells if c.startswith("### Insights"))
    decision = next(c for c in cells if c.startswith("## Part E"))
    (ROOT / "insights.md").write_text("# Insights: EDFA & SFP telemetry\n\n" + insights.split("\n", 1)[1].lstrip(), encoding="utf-8")
    (ROOT / "decision_log.md").write_text("# Decision log\n\n" + decision.split("\n", 1)[1].lstrip(), encoding="utf-8")
    generated = ROOT / "outputs" / "preprocessing_log.md"
    if generated.exists():
        shutil.copy(generated, ROOT / "preprocessing_log.md")
    print("wrote insights.md, decision_log.md, preprocessing_log.md")


def build_notebook(execute: bool) -> None:
    nb = ROOT / "pdm_notebook.ipynb"
    subprocess.run([sys.executable, "-m", "jupytext", "--to", "ipynb", "--output", str(nb), str(SRC)], check=True)
    if execute:
        subprocess.run([sys.executable, "-m", "nbconvert", "--to", "notebook", "--execute", "--inplace",
                        "--ExecutePreprocessor.timeout=900", str(nb)], check=True, cwd=ROOT)
    print("wrote", nb.name, "(executed)" if execute else "(not executed)")


if __name__ == "__main__":
    build_notebook(execute="--no-execute" not in sys.argv)  # executing the notebook regenerates outputs/
    export_markdown()
